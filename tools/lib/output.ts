// Writes build/: walkthroughs, profile journeys, report and bundle. All output is deterministic.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Content } from './content.js';
import type { Flows } from './flows.js';
import { formatIssue, type Issues } from './issues.js';
import type { JourneyResult } from './journeys.js';
import { factsCell, NOTICE, renderDiagnosisIndex, renderDiagnosisPath, renderRoutineCheck, renderTutorialIndex, renderTutorialPath } from './render.js';
import { ALL_RULES } from './rules.js';

export interface Outputs {
  files: Map<string, string>; // repo-relative path -> content
}

export function buildOutputs(c: Content, flows: Flows, profiles: Map<string, { markdown: string; results: JourneyResult[] }>): Outputs {
  const files = new Map<string, string>();
  for (const t of flows.tutorials) {
    files.set(`build/walkthroughs/${t.id}/index.md`, renderTutorialIndex(c, t));
    for (const p of t.paths) files.set(`build/walkthroughs/${t.id}/${p.id}.md`, renderTutorialPath(c, t, p));
  }
  for (const d of flows.diagnoses) {
    files.set(`build/walkthroughs/${d.id}/index.md`, renderDiagnosisIndex(c, d));
    for (const p of d.paths) files.set(`build/walkthroughs/${d.id}/${p.id}.md`, renderDiagnosisPath(c, d, p));
  }
  for (const id of c.checks.keys()) files.set(`build/walkthroughs/${id}/${id}.md`, renderRoutineCheck(c, id));
  for (const [id, p] of profiles) files.set(`build/walkthroughs/profiles/${id}.md`, p.markdown);
  return { files };
}

export function renderReport(c: Content, flows: Flows, profiles: Map<string, { results: JourneyResult[] }>, issues: Issues): string {
  const L: string[] = ['# Build report', '', '> Generated by `npm run check`. Do not edit by hand.', '', `> ${NOTICE}`, ''];
  const errors = issues.errors.length;
  L.push('## Summary', '');
  L.push(`- Result: **${errors ? `FAILED, ${errors} error(s)` : 'passed'}**, ${issues.warnings.length} warning(s)`);
  L.push(`- Files validated: ${c.files.length}`);
  L.push(`- 3D names checked against: \`${c.catalog.source}\``);
  L.push(`- Bundle: ${errors ? 'not written (errors)' : '`build/bundle.json`'}`, '');

  L.push('## Flows', '', '| Flow | Kind | Paths | Complete paths | Time of complete paths | Stop paths | Exits before the first step |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const t of flows.tutorials) {
    const complete = t.paths.filter((p) => p.variant.ending === 'complete');
    const mins = complete.map((p) => p.minutes);
    const range = mins.length ? `${Math.min(...mins)} to ${Math.max(...mins)} min` : '-';
    L.push(`| [${t.id}](walkthroughs/${t.id}/index.md) | tutorial | ${t.paths.length} | ${complete.length} | ${range} | ${t.paths.length - complete.length} | ${t.exits.length} |`);
  }
  for (const d of flows.diagnoses) {
    const mins = d.paths.map((p) => p.minutes);
    const range = mins.length ? `${Math.min(...mins)} to ${Math.max(...mins)} min` : '-';
    L.push(`| [${d.id}](walkthroughs/${d.id}/index.md) | diagnosis | ${d.paths.length} | ${d.paths.length} | ${range} | - | ${d.exits.length} |`);
  }
  for (const id of c.checks.keys()) L.push(`| [${id}](walkthroughs/${id}/${id}.md) | routine check | - | - | - | - | - |`);
  L.push('');

  L.push('## Time per bike and choice (complete paths)', '', '| Flow | Combination | Time |', '| --- | --- | --- |');
  for (const t of flows.tutorials) for (const p of t.paths.filter((x) => x.variant.ending === 'complete')) L.push(`| ${t.id} | \`${p.combo.baseId}\` | ${p.minutes} min |`);
  L.push('');

  L.push('## Where bikes end at a shop or not covered', '', 'Use this list to decide what to cover next.', '', '| Flow | Bike | Exit | Message |', '| --- | --- | --- | --- |');
  for (const f of [...flows.tutorials, ...flows.diagnoses]) {
    for (const e of f.exits) {
      L.push(`| ${f.id} | ${factsCell(c, e.combo)} | ${e.exit.kind} | ${e.exit.message} |`);
    }
  }
  L.push('');

  L.push('## Profiles', '', '| Profile | Journey | Ends | Time | Questions asked |', '| --- | --- | --- | --- | --- |');
  let total = 0;
  let shopOrNot = 0;
  for (const [id, p] of profiles) {
    for (const r of p.results) {
      total++;
      if (/shop|not covered|stop/.test(r.ending)) shopOrNot++;
      L.push(`| [${id}](walkthroughs/profiles/${id}.md) | ${r.title} | ${r.ending} | ${r.minutes} min | ${r.questions} |`);
    }
  }
  L.push('', `Journeys that end at a shop, a stop or not covered: ${shopOrNot} of ${total}.`, '');

  L.push('## Rules', '', '| Rule | Result | Meaning |', '| --- | --- | --- |');
  const count = new Map<string, number>();
  for (const i of issues.errors) count.set(i.rule, (count.get(i.rule) ?? 0) + 1);
  const ruleIds = [...new Set([...Object.keys(ALL_RULES), ...count.keys()])];
  for (const r of ruleIds) {
    const n = count.get(r) ?? 0;
    L.push(`| \`${r}\` | ${n ? `**${n} error(s)**` : 'pass'} | ${ALL_RULES[r] ?? ''} |`);
  }
  L.push('');

  const open: string[] = [];
  for (const j of c.jobs.values()) if (/^<.*>$/.test(j.def.shop.price_eur)) open.push(`- Price for job \`${j.def.id}\` is a placeholder.`);
  if (open.length) L.push('## Open placeholders', '', ...open, '');

  if (issues.list.length) {
    L.push('## Issues', '', '```', ...issues.list.map(formatIssue), '```', '');
  }
  return L.join('\n');
}

export function buildBundle(c: Content): string {
  const defs = (m: Map<string, { def: any }>) => [...m.values()].map((e) => e.def);
  const tutorials = [...c.tutorials.values()].map((t) => {
    const resolve = (cs: any): any => {
      const out: any = { ...cs };
      if (cs.include) {
        const cf = t.cases.get(cs.include);
        delete out.include;
        out.case = { name: cs.include.replace(/^cases\//, '').replace(/\.yaml$/, ''), sequence: cf?.data.sequence ?? [], finish: cf?.data.finish ?? [] };
      }
      if (cs.cases) out.cases = cs.cases.map(resolve);
      return out;
    };
    return { ...t.def, cases: t.def.cases.map(resolve) };
  });
  const payload = {
    facts: defs(c.facts),
    choices: defs(c.choices),
    states: defs(c.states),
    tools: defs(c.tools),
    parts: defs(c.parts),
    inspections: defs(c.inspections),
    jobs: defs(c.jobs),
    steps: defs(c.steps),
    procedures: defs(c.procedures),
    tutorials,
    diagnoses: defs(c.diagnoses),
    checks: defs(c.checks),
  };
  const hash = createHash('sha256').update(JSON.stringify(payload)).digest('hex').slice(0, 16);
  return JSON.stringify({ format: 1, content_hash: hash, notice: NOTICE, unverified: true, ...payload }, null, 2) + '\n';
}

export function writeOutputs(root: string, outputs: Outputs, report: string, bundle: string | null): void {
  rmSync(join(root, 'build/walkthroughs'), { recursive: true, force: true });
  const write = (rel: string, text: string) => {
    const abs = join(root, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text.endsWith('\n') ? text : `${text}\n`, 'utf8');
  };
  for (const [rel, text] of outputs.files) write(rel, text);
  write('build/report.md', report);
  const bundlePath = join(root, 'build/bundle.json');
  if (bundle) write('build/bundle.json', bundle);
  else if (existsSync(bundlePath)) rmSync(bundlePath);
}

export function pathCount(flows: Flows): number {
  return flows.tutorials.reduce((s, t) => s + t.paths.length, 0) + flows.diagnoses.reduce((s, d) => s + d.paths.length, 0);
}
